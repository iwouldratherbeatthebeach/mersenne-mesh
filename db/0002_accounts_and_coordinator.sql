PRAGMA defer_foreign_keys = true;

-- Move contributor ownership from mutable email addresses to Auth.js user IDs.
CREATE TABLE IF NOT EXISTS profiles_v2 (
  user_id TEXT NOT NULL PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  display_name TEXT NOT NULL,
  public_handle TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT OR IGNORE INTO profiles_v2 (user_id, email, display_name, public_handle, created_at, updated_at)
SELECT u.id, lower(p.email), p.display_name, p.public_handle, p.created_at, p.updated_at
FROM profiles p
JOIN users u ON lower(u.email) = lower(p.email);

CREATE TABLE IF NOT EXISTS contributions_v2 (
  id INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
  user_id TEXT NOT NULL REFERENCES profiles_v2(user_id) ON DELETE CASCADE,
  work_unit_id TEXT NOT NULL,
  exponent INTEGER NOT NULL,
  engine TEXT NOT NULL CHECK (engine IN ('cpu', 'gpu')),
  cpu_core_milliseconds INTEGER NOT NULL DEFAULT 0,
  gpu_milliseconds INTEGER NOT NULL DEFAULT 0,
  candidates INTEGER NOT NULL,
  factors_json TEXT NOT NULL DEFAULT '[]',
  factor_count INTEGER NOT NULL DEFAULT 0,
  verified INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (user_id, work_unit_id)
);

INSERT OR IGNORE INTO contributions_v2 (
  id, user_id, work_unit_id, exponent, engine,
  cpu_core_milliseconds, gpu_milliseconds, candidates,
  factors_json, factor_count, verified, created_at
)
SELECT c.id, u.id, c.work_unit_id, c.exponent, c.engine,
       c.cpu_core_milliseconds, c.gpu_milliseconds, c.candidates,
       c.factors_json, c.factor_count, c.verified, c.created_at
FROM contributions c
JOIN users u ON lower(u.email) = lower(c.user_email);

DROP TABLE IF EXISTS contributions;
DROP TABLE IF EXISTS profiles;
ALTER TABLE profiles_v2 RENAME TO profiles;
ALTER TABLE contributions_v2 RENAME TO contributions;
CREATE INDEX IF NOT EXISTS contributions_user_created_idx
  ON contributions (user_id, created_at);

-- Important auth, profile, lease, and accepted/rejected contribution events are
-- persisted here because Pages tail logs are real-time streams and are not a ledger.
CREATE TABLE IF NOT EXISTS audit_events (
  id INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
  user_id TEXT REFERENCES users(id) ON DELETE SET NULL,
  event TEXT NOT NULL,
  metadata_json TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS audit_events_user_created_idx
  ON audit_events (user_id, created_at);
CREATE INDEX IF NOT EXISTS audit_events_event_created_idx
  ON audit_events (event, created_at);

-- Coordinator queue. Validation units deliberately allow many independent
-- replicas. Production discovery units can later use target_replicas=1 and a
-- separate network name after reconciliation with established searches.
CREATE TABLE IF NOT EXISTS work_units (
  id TEXT NOT NULL PRIMARY KEY,
  network TEXT NOT NULL DEFAULT 'validation',
  exponent INTEGER NOT NULL,
  start_k INTEGER NOT NULL,
  count INTEGER NOT NULL,
  expected_candidates INTEGER NOT NULL,
  expected_factors_json TEXT NOT NULL DEFAULT '[]',
  target_replicas INTEGER NOT NULL DEFAULT 1,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS work_leases (
  id TEXT NOT NULL PRIMARY KEY,
  work_unit_id TEXT NOT NULL REFERENCES work_units(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  engine TEXT NOT NULL CHECK (engine IN ('cpu', 'gpu')),
  status TEXT NOT NULL DEFAULT 'leased' CHECK (status IN ('leased', 'completed', 'expired')),
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TEXT
);
CREATE INDEX IF NOT EXISTS work_leases_unit_status_idx ON work_leases (work_unit_id, status);
CREATE INDEX IF NOT EXISTS work_leases_user_status_idx ON work_leases (user_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS work_leases_one_active_per_user ON work_leases (user_id) WHERE status = 'leased';

